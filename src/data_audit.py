"""
src/data_audit.py
=================
Loads Training.csv and Testing.csv from data/raw/ and writes a comprehensive
audit report to docs/data_audit.md.

Run:
    python src/data_audit.py

The script never modifies the raw files; it only reads them.
"""

import os
from collections import defaultdict

import pandas as pd

# ------------------------------------------------------------------
# 1. Load raw data
# ------------------------------------------------------------------
RAW_DIR = os.path.join("data", "raw")
DOCS_DIR = "docs"

train_path = os.path.join(RAW_DIR, "Training.csv")
test_path  = os.path.join(RAW_DIR, "Testing.csv")

print("Loading Training.csv ...")
train = pd.read_csv(train_path)
print("Loading Testing.csv ...")
test  = pd.read_csv(test_path)

# ------------------------------------------------------------------
# 2. Helper to build the markdown sections
# ------------------------------------------------------------------
lines = []

def h1(title):
    lines.append(f"# {title}\n")

def h2(title):
    lines.append(f"## {title}\n")

def h3(title):
    lines.append(f"### {title}\n")

def para(text):
    lines.append(f"{text}\n")

def code(text):
    lines.append(f"```\n{text}\n```\n")

# ------------------------------------------------------------------
# 3. Title
# ------------------------------------------------------------------
h1("Data Audit – Disease Prediction Dataset")
para("Auto-generated by `src/data_audit.py`. Raw files are never modified.")

# ------------------------------------------------------------------
# 4. Shapes
# ------------------------------------------------------------------
h2("4.1 – Dataset Shapes")
para("| File | Rows | Columns |")
para("|------|------|---------|")
para(f"| Training.csv | {train.shape[0]} | {train.shape[1]} |")
para(f"| Testing.csv  | {test.shape[0]}  | {test.shape[1]}  |")

# ------------------------------------------------------------------
# 5. Column name problems (empty, unnamed, duplicates)
# ------------------------------------------------------------------
h2("4.2 – Column Name Issues")

def col_issues(df, name):
    cols = df.columns.tolist()
    empty_cols    = [c for c in cols if str(c).strip() == ""]
    unnamed_cols  = [c for c in cols if str(c).startswith("Unnamed:")]
    dup_cols      = [c for c in cols if cols.count(c) > 1]
    return empty_cols, unnamed_cols, list(set(dup_cols))

train_empty, train_unnamed, train_dup = col_issues(train, "Training")
test_empty,  test_unnamed,  test_dup  = col_issues(test,  "Testing")

para("**Training.csv**")
para(f"- Empty column names: `{train_empty}`")
para(f"- Unnamed columns  : `{train_unnamed}`")
para(f"- Duplicate columns: `{train_dup}`")

para("**Testing.csv**")
para(f"- Empty column names: `{test_empty}`")
para(f"- Unnamed columns  : `{test_unnamed}`")
para(f"- Duplicate columns: `{test_dup}`")

# ------------------------------------------------------------------
# 6. Missing values
# ------------------------------------------------------------------
h2("4.3 – Missing Values")

train_null = train.isnull().sum()
test_null  = test.isnull().sum()

train_missing_cols = train_null[train_null > 0]
test_missing_cols  = test_null[test_null  > 0]

if len(train_missing_cols) == 0:
    para("Training.csv: **No missing values** in any column.")
else:
    para("Training.csv columns with missing values:")
    code(str(train_missing_cols))

if len(test_missing_cols) == 0:
    para("Testing.csv: **No missing values** in any column.")
else:
    para("Testing.csv columns with missing values:")
    code(str(test_missing_cols))

# ------------------------------------------------------------------
# 7. Value types
# ------------------------------------------------------------------
h2("4.4 – Column Value Types (dtypes)")

# Count how many columns of each dtype in each file
def dtype_summary(df):
    return df.dtypes.value_counts().to_dict()

train_dtypes = dtype_summary(train)
test_dtypes  = dtype_summary(test)

para("**Training.csv dtypes:**")
for dtype, count in train_dtypes.items():
    para(f"  - `{dtype}`: {count} columns")

para("**Testing.csv dtypes:**")
for dtype, count in test_dtypes.items():
    para(f"  - `{dtype}`: {count} columns")

# ------------------------------------------------------------------
# 8. Disease list (prognosis column)
# ------------------------------------------------------------------
h2("4.5 – Disease List (prognosis column)")

LABEL_COL = "prognosis"

train_disease_counts = train[LABEL_COL].value_counts().sort_index()
test_disease_counts  = test[LABEL_COL].value_counts().sort_index()

all_diseases = sorted(
    set(train_disease_counts.index.tolist()) |
    set(test_disease_counts.index.tolist())
)

para(f"Total unique disease classes found: **{len(all_diseases)}**\n")
para("| # | Disease | Train rows | Test rows |")
para("|---|---------|-----------|-----------|")
for i, disease in enumerate(all_diseases, 1):
    tr = train_disease_counts.get(disease, 0)
    te = test_disease_counts.get(disease, 0)
    para(f"| {i} | {disease} | {tr} | {te} |")

# ------------------------------------------------------------------
# 9. Symptom column list
# ------------------------------------------------------------------
h2("4.6 – Symptom Columns")

# All columns except prognosis are symptom columns
symptom_cols = [c for c in train.columns if c != LABEL_COL]
para(f"Number of symptom columns: **{len(symptom_cols)}**\n")
para("```")
for s in symptom_cols:
    lines[-1] += ""   # skip, we'll build it below
# Rebuild: code block
lines.append("```\n" + "\n".join(symptom_cols) + "\n```\n")

# ------------------------------------------------------------------
# 10. Duplicate rows
# ------------------------------------------------------------------
h2("4.7 – Duplicate Rows")

train_dups = train.duplicated().sum()
test_dups  = test.duplicated().sum()

para("| File | Duplicate rows |")
para("|------|---------------|")
para(f"| Training.csv | {train_dups} |")
para(f"| Testing.csv  | {test_dups} |")

# ------------------------------------------------------------------
# 11. Rows shared between train and test
# ------------------------------------------------------------------
h2("4.8 – Rows Shared Between Train and Test")

# Merge on all columns (exact row match)
train_common = train.copy()
test_common  = test.copy()
merged = pd.merge(train_common, test_common, how="inner")
shared = len(merged)

para(f"Exact rows present in **both** Training.csv and Testing.csv: **{shared}**")

# ------------------------------------------------------------------
# 12. Symptoms never equal to 1 (all-zero columns)
# ------------------------------------------------------------------
h2("4.9 – Symptoms That Are Never 1")

# Check in Training set (reference for model training)
train_symptom_data = train[symptom_cols]
never_one_train = [c for c in symptom_cols if train_symptom_data[c].max() == 0]

test_symptom_data = test[symptom_cols] if all(c in test.columns for c in symptom_cols) else pd.DataFrame()
never_one_test = (
    [c for c in symptom_cols if test_symptom_data[c].max() == 0]
    if not test_symptom_data.empty else []
)

para(f"**Training.csv** – columns where max value == 0 (always absent): `{never_one_train}`")
para(f"**Testing.csv**  – columns where max value == 0 (always absent): `{never_one_test}`")

# ------------------------------------------------------------------
# 13. Disease name inconsistencies (typos, case, whitespace)
# ------------------------------------------------------------------
h2("4.10 – Disease Name Inconsistencies")

all_train_raw = train[LABEL_COL].unique().tolist()
all_test_raw  = test[LABEL_COL].unique().tolist()
all_raw       = list(set(all_train_raw + all_test_raw))

# Check for leading/trailing whitespace
whitespace_issues = [d for d in all_raw if d != d.strip()]

# Check for case inconsistencies: group names that are equal after lowercasing
lower_groups = defaultdict(list)
for d in all_raw:
    lower_groups[d.lower().strip()].append(d)
case_issues = {k: v for k, v in lower_groups.items() if len(v) > 1}

# Names only in train but not test (may indicate class imbalance or mismatch)
only_in_train = set(all_train_raw) - set(all_test_raw)
only_in_test  = set(all_test_raw)  - set(all_train_raw)

para(f"**Whitespace issues** (name != name.strip()): `{whitespace_issues}`")
para(f"**Case inconsistencies** (same name, different capitalisation): `{case_issues}`")
para(f"**Diseases only in Training.csv** (not in Testing.csv): `{sorted(only_in_train)}`")
para(f"**Diseases only in Testing.csv**  (not in Training.csv): `{sorted(only_in_test)}`")

# ------------------------------------------------------------------
# 14. Write the report
# ------------------------------------------------------------------
os.makedirs(DOCS_DIR, exist_ok=True)
out_path = os.path.join(DOCS_DIR, "data_audit.md")

with open(out_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print(f"\n[OK] Audit written to {out_path}")
print(f"   Training shape : {train.shape}")
print(f"   Testing shape  : {test.shape}")
print(f"   Diseases found : {len(all_diseases)}")
print(f"   Symptom columns: {len(symptom_cols)}")
